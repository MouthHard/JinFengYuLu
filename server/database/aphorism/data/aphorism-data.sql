SELECT a.`id`, c.`id`
FROM `aphorism` a
CROSS JOIN `category` c
WHERE c.`type` = 'aphorism_form'
  AND c.`name` != '全部诗词'
  AND a.`is_active` = 1
  AND a.`form` IS NOT NULL
  AND (
    (c.`name` = '诗'     AND (a.`form` LIKE '%五绝%' OR a.`form` LIKE '%七绝%' OR a.`form` LIKE '%五律%' OR a.`form` LIKE '%七律%' OR a.`form` LIKE '%五言%' OR a.`form` LIKE '%七言%' OR a.`form` LIKE '%四言%' OR a.`form` LIKE '%古体%' OR a.`form` LIKE '%诗经%' OR a.`form` LIKE '%乐府%' OR a.`form` LIKE '%歌行%'))
    OR (c.`name` = '词'     AND (a.`form` = '词' OR a.`form` LIKE '%小令%' OR a.`form` LIKE '%中调%' OR a.`form` LIKE '%长调%'))
    OR (c.`name` = '曲'     AND (a.`form` LIKE '%散曲%' OR a.`form` LIKE '%杂剧%'))
    OR (c.`name` = '其他韵文' AND (a.`form` LIKE '%赋%' OR a.`form` LIKE '%骚%' OR a.`form` LIKE '%楚辞%' OR a.`form` LIKE '%铭%' OR a.`form` = '歌'))
    OR (c.`name` = '特殊形式' AND (a.`form` LIKE '%回文%' OR a.`form` LIKE '%藏头%' OR a.`form` LIKE '%宝塔%'))
  );

-- 4.3 标签分类关联（题材/情感/流派/用途，基于 aphorism_tag）
INSERT INTO `aphorism_category_relation` (`poem_id`, `category_id`)
SELECT DISTINCT at.`poem_id`, c.`id`
FROM `aphorism_tag` at
JOIN `tmp_tag_category_map` m ON at.`tag` = m.`tag`
JOIN `category` c ON c.`type` = m.`category_type` AND c.`name` = m.`category_name`
WHERE c.`name` != '全部诗词'
  AND c.`is_active` = 1;

-- 清理临时表
DROP TEMPORARY TABLE IF EXISTS `tmp_tag_category_map`;

