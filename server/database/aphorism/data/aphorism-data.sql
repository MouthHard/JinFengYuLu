INSERT INTO `aphorism_category_relation` (`poem_id`, `category_id`)
SELECT a.`id`, c.`id`
FROM `aphorism` a
CROSS JOIN `category` c
WHERE c.`type` = 'aphorism_dynasty'
  AND c.`name` != '全部诗词'
  AND a.`is_active` = 1
  AND (
    (c.`name` = '先秦'     AND a.`dynasty` IN ('先秦', '夏', '商', '西周', '东周', '春秋', '战国'))
    OR (c.`name` = '秦汉'     AND a.`dynasty` IN ('秦', '西汉', '东汉'))
    OR (c.`name` = '魏晋'     AND a.`dynasty` IN ('魏晋', '西晋', '东晋', '三国', '魏', '蜀', '吴'))
    OR (c.`name` = '南北朝'   AND a.`dynasty` IN ('南北朝', '南朝', '北朝', '宋', '齐', '梁', '陈', '北魏', '东魏', '西魏', '北齐', '北周'))
    OR (c.`name` = '隋唐'     AND a.`dynasty` IN ('隋', '唐'))
    OR (c.`name` = '五代十国' AND a.`dynasty` IN ('五代十国', '后梁', '后唐', '后晋', '后汉', '后周'))
    OR (c.`name` = '宋辽金'   AND a.`dynasty` IN ('北宋', '南宋', '辽', '西夏', '金'))
    OR (c.`name` = '元明清'   AND a.`dynasty` IN ('元', '明', '清'))
    OR (c.`name` = '近现代'   AND a.`dynasty` IN ('民国', '现代'))
  );

